import { useEffect, useState, type ReactNode } from 'react';
import { screen } from '@testing-library/react';
import { MockConfigApi } from '@backstage/test-utils';
import { useApi } from '@backstage/core-plugin-api';
import { compatWrapper } from '@backstage/core-compat-api';
import {
  discoverAvailableFeatures,
  resolveAsyncFeatures,
} from '@backstage/frontend-defaults';
import {
  createFrontendPlugin,
  createRouteRef,
  PageBlueprint,
} from '@backstage/frontend-plugin-api';
import { renderTestApp } from '@backstage/frontend-test-utils';
import portalPlugin from '@ansible/portal-core/alpha';
import {
  EntityDetailTabBlueprint,
  portalContributionsApiRef,
  type EntityDetailTabDescriptor,
} from '@ansible/portal-extension-api/alpha';
import { optionalContributorLoader } from './composition';

// These mocks fail if the reduced profile evaluates optional native entries.
// Legacy package roots are never imported by this test or its source loader.
jest.mock('@ansible/portal-scaffolder/alpha', () => {
  throw new Error('Core profile must not evaluate portal-scaffolder');
});
jest.mock('@ansible/plugin-backstage-apme/alpha', () => {
  throw new Error('Core profile must not evaluate APME');
});
jest.mock('@ansible/plugin-backstage-rhaap/alpha', () => {
  throw new Error('Core profile must not evaluate the Ansible page');
});

const manifest: EntityDetailTabDescriptor['manifest'] = {
  id: 'discovered-example',
  version: '1.0.0',
  apiVersion: '0.1.0',
  entitlements: [],
  capabilities: [
    {
      id: 'discovered-example.quality',
      ownerPlugin: 'discovered-example',
      experienceId: 'content-quality-assessment',
      displayName: 'Discovered quality',
      description: 'Independent native contribution',
      minimumHostApiVersion: '0.1.0',
      appliesToContentTypes: ['playbook-repository'],
      entryPoints: [
        {
          id: 'discovered-example.findings',
          kind: 'entity-tab',
          surface: 'entity-page',
          label: 'Discovered findings',
          appliesToContentTypes: ['playbook-repository'],
          launches: { type: 'slot', targetSlot: 'entity.detail.tabs' },
        },
      ],
    },
  ],
};

const entityContext = {
  contentType: 'playbook-repository',
  entity: {
    apiVersion: 'backstage.io/v1alpha1',
    kind: 'Component',
    metadata: { name: 'independent-repository' },
  },
};

function DiscoveredContribution({
  descriptor,
}: {
  descriptor: EntityDetailTabDescriptor;
}) {
  const [content, setContent] = useState<ReactNode>(null);
  useEffect(() => {
    let current = true;
    descriptor.loader(entityContext).then(element => {
      if (current) setContent(element);
    });
    return () => {
      current = false;
    };
  }, [descriptor]);
  return <>{content}</>;
}

function DiscoveredPage() {
  const contributions = useApi(portalContributionsApiRef);
  return (
    <>
      <h1>Discovered independent page</h1>
      {contributions.tabs.map(tab => (
        <DiscoveredContribution key={tab.entryPointId} descriptor={tab} />
      ))}
    </>
  );
}

const pageLoader = jest.fn(async () => compatWrapper(<DiscoveredPage />));
const tabLoader = jest.fn(async () => <div>Independent findings</div>);
const independentPlugin = createFrontendPlugin({
  pluginId: 'discovered-example',
  extensions: [
    PageBlueprint.make({
      params: {
        path: '/discovered-example',
        routeRef: createRouteRef(),
        loader: pageLoader,
      },
    }),
    EntityDetailTabBlueprint.make({
      name: 'findings',
      params: {
        manifest,
        capabilityId: 'discovered-example.quality',
        entryPointId: 'discovered-example.findings',
        attachment: 'entity.detail.tabs',
        loader: tabLoader,
      },
    }),
  ],
});

const discoveryKey = '__@backstage/discovered__';

describe('additional source-app discovery on the core development profile', () => {
  let previousDiscovery: PropertyDescriptor | undefined;

  beforeEach(() => {
    jest.clearAllMocks();
    previousDiscovery = Object.getOwnPropertyDescriptor(window, discoveryKey);
    // Test-only fixture for the module list normally generated by Backstage CLI.
    Object.defineProperty(window, discoveryKey, {
      configurable: true,
      value: {
        modules: [
          { name: '@example/independent', default: independentPlugin },
          { name: '@example/not-a-plugin', default: {} },
        ],
      },
    });
  });

  afterEach(() => {
    if (previousDiscovery) {
      Object.defineProperty(window, discoveryKey, previousDiscovery);
    } else {
      Reflect.deleteProperty(window, discoveryKey);
    }
  });

  async function resolveDiscovered(packages?: {
    include: string[];
    exclude?: string[];
  }) {
    const config = new MockConfigApi({
      portal: { development: { profile: 'core' } },
      ...(packages ? { app: { packages } } : {}),
    });
    return resolveAsyncFeatures({
      config,
      features: [
        portalPlugin,
        optionalContributorLoader,
        ...discoverAvailableFeatures(config).features,
      ],
    });
  }

  it('discovers an extra native contributor and renders it through the unchanged portal host', async () => {
    const { features } = await resolveDiscovered({
      include: ['@example/independent'],
    });
    expect(features).toEqual([portalPlugin, independentPlugin]);
    expect(pageLoader).not.toHaveBeenCalled();
    await renderTestApp({
      features,
      config: { portal: { landingPage: '/discovered-example' } },
      initialRouteEntries: ['/'],
    });
    expect(
      await screen.findByRole('heading', {
        name: 'Discovered independent page',
      }),
    ).toBeTruthy();
    expect(await screen.findByText('Independent findings')).toBeTruthy();
    expect(pageLoader).toHaveBeenCalledTimes(1);
    expect(tabLoader).toHaveBeenCalledWith(entityContext);
  });

  it('does not rediscover contributors unless package inclusion is enabled', async () => {
    expect((await resolveDiscovered()).features).toEqual([portalPlugin]);
    expect(pageLoader).not.toHaveBeenCalled();
  });

  it('honors explicit package selection and filters non-feature module exports', async () => {
    expect(
      (await resolveDiscovered({ include: ['@example/not-a-plugin'] }))
        .features,
    ).toEqual([portalPlugin]);
    expect(pageLoader).not.toHaveBeenCalled();
  });

  it('excludes disabled packages before resolving their native features', async () => {
    expect(
      (
        await resolveDiscovered({
          include: ['@example/independent'],
          exclude: ['@example/independent'],
        })
      ).features,
    ).toEqual([portalPlugin]);
    expect(pageLoader).not.toHaveBeenCalled();
  });
});
