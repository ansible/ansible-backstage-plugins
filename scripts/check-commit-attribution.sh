#!/usr/bin/env sh
# Reject Co-authored-by trailers that attribute AI coding tools.
# Human co-authors are allowed; use Assisted-by for AI assistance instead.
#
# Uses git interpret-trailers to parse trailers correctly, handling
# whitespace-before-colon and folded multi-line forms.
set -eu

commit_msg_file="${1:-${PRE_COMMIT_COMMIT_MSG_FILENAME:-}}"

if [ -z "$commit_msg_file" ] || [ ! -f "$commit_msg_file" ]; then
  echo "check-commit-attribution: missing commit message file" >&2
  exit 1
fi

ai_tool_pattern='(claude|anthropic|cursor|copilot|github-copilot|openai|chatgpt|gpt-|gemini|codex|windsurf|cody|devin|aider|tabnine|sourcegraph|continue-dev|amazon[[:space:]]q|codeium|replit|bolt\.new|\[bot\]|@anthropic\.com|@cursor\.com|@openai\.com|@github\.com/apps/)'

# Parse and unfold trailers, then check only Co-authored-by values.
coauthor_values="$(git interpret-trailers --parse --unfold < "$commit_msg_file" 2>/dev/null \
  | grep -iE '^co-authored-by:' \
  | sed 's/^[Cc]o-[Aa]uthored-[Bb]y:[[:space:]]*//' || true)"

if [ -z "$coauthor_values" ]; then
  exit 0
fi

violation_count=0
while IFS= read -r value; do
  if printf '%s\n' "$value" | grep -iqE "$ai_tool_pattern"; then
    violation_count=$((violation_count + 1))
  fi
done <<EOF
$coauthor_values
EOF

if [ "$violation_count" -gt 0 ]; then
  echo "commit-msg: Co-authored-by is not allowed for AI tools." >&2
  echo >&2
  echo "Use one of these instead (no email required):" >&2
  echo "  Assisted-by: <name of code assistant>" >&2
  echo "  Generated by <name of code assistant>" >&2
  echo >&2
  echo "Found $violation_count AI tool Co-authored-by trailer(s)." >&2
  exit 1
fi

exit 0
